"""
clean.py -- frees the disk space the benchmarks take, without losing any result.

    python clean.py            # dry run: lists what it would delete and how much space it frees
    python clean.py --apply    # deletes it

Run from benchmarks/. What goes (all of it is rebuilt automatically the next time a board is used):
    runs/**/.pio/             PlatformIO builds of every chip project (ESP-IDF builds: ~100 MB each)
    runs/**/managed_components/, runs/**/build/   ESP-IDF downloads and builds, if any
    **/__pycache__/           Python bytecode
What stays, always (never entered): results/, models/, Python environments (env_*, .venv, venv, any folder with
a pyvenv.cfg) and .git/. In detail:
    results/                  every published .json (the *_tflite.py scripts read them by name)
    models/                   the original FP32 models
    runs/*/ (the rest)        trained and exported models (model_binarized.pth, model_symbex.h, *.json), the chip
                              projects' sources and sdkconfig: everything needed to re-measure without retraining
It also writes a .gitignore here (runs/, models/, data/, __pycache__/) if there is none.
"""
import argparse
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
DELETE_DIRS = {".pio", "managed_components", "build", "__pycache__"}
NEVER = {"results", "models", ".venv", "venv", ".git"}   # never entered, whatever they contain
GITIGNORE = """# generated by the benchmarks (rebuilt automatically); results/ is what gets published
*/runs/
*/models/
data/
__pycache__/
*.pyc
"""


def size_of(path):
    total = 0
    for d, _, files in os.walk(path):
        for f in files:
            try:
                total += os.path.getsize(os.path.join(d, f))
            except OSError:
                pass
    return total


def human(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.1f} {unit}" if unit != "B" else f"{n} B"
        n /= 1024


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="delete (without it: only list)")
    args = ap.parse_args()
    found = []
    for d, dirs, _ in os.walk(HERE):
        # never enter results/, models/ or a Python environment (a folder with pyvenv.cfg, or named env_*)
        dirs[:] = [x for x in dirs if x not in NEVER and not x.startswith("env_")
                   and not os.path.exists(os.path.join(d, x, "pyvenv.cfg"))]
        for x in list(dirs):
            if x in DELETE_DIRS and (x == "__pycache__" or f"{os.sep}runs{os.sep}" in os.path.join(d, x) + os.sep):
                found.append(os.path.join(d, x))
                dirs.remove(x)                      # do not walk into what is going away
    total = 0
    by_bench = {}
    for p in found:
        s = size_of(p)
        total += s
        bench = os.path.relpath(p, HERE).split(os.sep)[0]
        by_bench[bench] = by_bench.get(bench, 0) + s
    print(f"[*] {'deleting' if args.apply else 'would delete'} {len(found)} folders, {human(total)}:")
    for bench, s in sorted(by_bench.items(), key=lambda x: -x[1]):
        print(f"      {bench:<26}{human(s):>10}")
    if args.apply:
        for p in found:
            shutil.rmtree(p, ignore_errors=True)
        print("[*] done")
    else:
        print("    (dry run: nothing deleted; run with --apply)")
    gi = os.path.join(HERE, ".gitignore")
    if not os.path.exists(gi):
        if args.apply:
            open(gi, "w").write(GITIGNORE)
            print(f"[*] wrote {gi}")
        else:
            print(f"    would write {gi} (runs/, models/, data/, __pycache__/)")


if __name__ == "__main__":
    main()
