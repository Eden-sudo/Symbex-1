"""
ucbnn_check.py -- did we understand the data layout of ultracompactBNN (Daghero et al., CF 2021)? Checked on this PC.

    python ucbnn_check.py --repo ~/Proyectos/ultracompactBNN
    python ucbnn_check.py --repo ~/Proyectos/ultracompactBNN --cases 200

Their templates read a data.h that the repository does not include (L_IN, C_IN, C_OUT, K_S, STRIDE, L_OUT, INPUT,
WEIGHTS, THRESHOLDS, OUTPUT). This writes it, for random layers, as their binary 1D convolution reads it:
    bit order    one continuous bit stream per buffer, the MOST significant bit of every word first
    input        time-major: element (t, c) is bit t * C_in + c
    weights      output channel after output channel, each K * C_in bits (k-major, then c), no padding between them
    output       time-major: element (t, o) is bit t * C_out + o
    rule         matches = popcount(XNOR(window, weights)) over the K * C_in bits; out = matches >= threshold (int16)
    borders      none: L_out = L_in - K + 1, stride 1
Then it compiles THEIR convolution (template_convolution1d_1bit: convolution1bit_NxM.c, xnorpop2x2g.c,
xnorpop4x1g.c) with plain gcc -- __builtin_pulp_cnt replaced by __builtin_popcount (the same count), rt/rt_api.h by an
empty stub -- and checks their output against the expected one, bit by bit. It checks the arithmetic and the layout,
not the cycles (those come from the PULP simulator, GVSOC).
"""
import argparse
import os
import shutil
import subprocess
import sys
import tempfile

import numpy as np


def msb_words(bits):
    """0/1 vector -> uint32 words, MSB first, zero padded to whole words"""
    n = -(-len(bits) // 32)
    pad = np.zeros(n * 32, dtype=np.uint8)
    pad[:len(bits)] = bits
    return np.packbits(pad, bitorder="big").view(">u4").astype(np.uint32)


def layer(rng, l_in, c_in, c_out, k):
    """a random layer and its expected output, as their kernel computes it"""
    x = rng.integers(0, 2, (l_in, c_in), dtype=np.uint8)
    w = rng.integers(0, 2, (c_out, k, c_in), dtype=np.uint8)
    l_out = l_in - k + 1
    n = k * c_in
    thr = rng.integers(n // 2 - n // 4, n // 2 + n // 4 + 1, c_out).astype(np.int16)
    win = np.stack([x[t:t + k].ravel() for t in range(l_out)])                 # (L_out, K*C_in)
    matches = (win[:, None, :] == w.reshape(c_out, n)[None]).sum(2)            # (L_out, C_out)
    out = (matches >= thr[None]).astype(np.uint8)
    return dict(L_IN=l_in, C_IN=c_in, C_OUT=c_out, K_S=k, STRIDE=1, L_OUT=l_out,
                INPUT=msb_words(x.ravel()), WEIGHTS=msb_words(w.ravel()), THRESHOLDS=thr, OUTPUT=msb_words(out.ravel()))


def data_h(d):
    arr = lambda v, fmt: "{" + ", ".join(fmt(int(a)) for a in v) + "}"
    hexa = lambda a: f"0x{a & 0xFFFFFFFF:08X}"
    return "\n".join([
        "/* generated by ucbnn_check.py: one binary 1D convolution layer in the ultracompactBNN layout */",
        *(f"#define {k} {d[k]}" for k in ("L_IN", "C_IN", "C_OUT", "K_S", "STRIDE", "L_OUT")),
        f"#define INPUT {arr(d['INPUT'], hexa)}",
        f"#define WEIGHTS {arr(d['WEIGHTS'], hexa)}",
        f"#define THRESHOLDS {arr(d['THRESHOLDS'], str)}",
        f"#define OUTPUT {arr(d['OUTPUT'], hexa)}", ""])


MAIN = r"""
#include <stdio.h>
#include <stdint.h>
#include "data.h"
#include "kernels.h"
/* the buffers as their data_allocation.h declares them, plus one spare word: their kernel reads one word past the end
   of the input and of the weights (masked out, never used) */
static const uint32_t input_data_int1[(C_IN * L_IN + 31) / 32 + 1] = INPUT;
static const uint32_t weights[(C_OUT * K_S * C_IN + 31) / 32 + 1] = WEIGHTS;
static uint32_t output[(C_OUT * L_OUT + 31) / 32] = {0};
static const int16_t thresholds[C_OUT] = THRESHOLDS;
static const uint32_t checksum[(C_OUT * L_OUT + 31) / 32] = OUTPUT;
int main(void) {
    conv_bin_1D_nopad_nodilation(input_data_int1, L_IN, C_IN, weights, C_OUT, K_S, STRIDE, output, L_OUT, thresholds);
    int bad = 0;
    for (int i = 0; i < (L_OUT * C_OUT + 31) / 32; i++) bad += output[i] != checksum[i];
    printf("%d\n", bad);
    return 0;
}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, help="the ultracompactBNN clone")
    ap.add_argument("--cases", type=int, default=60)
    args = ap.parse_args()
    src = os.path.join(os.path.expanduser(args.repo), "template_convolution1d_1bit", "gvsoc")
    files = [os.path.join(src, "src", f) for f in ("convolution1bit_NxM.c", "xnorpop2x2g.c", "xnorpop4x1g.c")]
    for f in files + [os.path.join(src, "include", "kernels.h")]:
        if not os.path.exists(f):
            sys.exit(f"[X] {f} not found: --repo must be the ultracompactBNN clone")
    rng = np.random.default_rng(0)
    # output channels: powers of 2, the sizes their library supports (the paper: "any power-of-2 as number of
    # channels"); with 5 or 7 output channels, checked on the PC, the step from the 4-channel blocks to the leftover
    # channels does not give the right output. Input channels: any (3 = a tri-axial accelerometer, as UniMiB-SHAR).
    shapes = [(32, 4, 8, 7), (151, 3, 8, 15), (64, 16, 16, 3), (128, 8, 32, 7), (40, 2, 4, 11), (64, 32, 32, 15)]
    while len(shapes) < args.cases:
        k = int(rng.choice([3, 5, 7, 11, 15]))
        shapes.append((int(rng.integers(k + 1, 160)), int(rng.choice([1, 2, 3, 4, 8, 16, 32])),
                       int(rng.choice([1, 2, 4, 8, 16, 32])), k))
    ok = 0
    with tempfile.TemporaryDirectory() as d:
        os.makedirs(os.path.join(d, "rt"))
        open(os.path.join(d, "rt", "rt_api.h"), "w").write("#include <stdint.h>\n#include <stdio.h>\n")
        os.makedirs(os.path.join(d, "include"))
        shutil.copy(os.path.join(src, "include", "kernels.h"), os.path.join(d, "include", "kernels.h"))
        os.makedirs(os.path.join(d, "src"))
        for f in files:
            shutil.copy(f, os.path.join(d, "src", os.path.basename(f)))
        open(os.path.join(d, "src", "main.c"), "w").write(MAIN)
        for i, (l_in, c_in, c_out, k) in enumerate(shapes[:args.cases]):
            open(os.path.join(d, "src", "data.h"), "w").write(data_h(layer(rng, l_in, c_in, c_out, k)))
            exe = os.path.join(d, "t")
            r = subprocess.run(["gcc", "-O2", "-w", "-I", d, "-I", os.path.join(d, "include"),
                                "-D__builtin_pulp_cnt(x)=__builtin_popcount(x)", "-o", exe]
                               + [os.path.join(d, "src", f) for f in ("main.c", "convolution1bit_NxM.c", "xnorpop2x2g.c",
                                                                      "xnorpop4x1g.c")], capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit("[X] their kernel did not compile with gcc:\n" + r.stderr[-2000:])
            bad = int(subprocess.run([exe], capture_output=True, text=True).stdout.strip() or -1)
            ok += bad == 0
            if bad != 0 or i < 6:
                print(f"    L_in {l_in:4d}  C_in {c_in:3d}  C_out {c_out:3d}  K {k:3d}:  "
                      + ("same output, bit by bit" if bad == 0 else f"{bad} words differ [X]"))
    print(f"\n[*] {ok}/{min(args.cases, len(shapes))} random layers: their kernel gives exactly the expected output"
          + ("  -> the layout is understood" if ok == min(args.cases, len(shapes)) else "  [X] the layout is NOT understood yet"))


if __name__ == "__main__":
    main()
